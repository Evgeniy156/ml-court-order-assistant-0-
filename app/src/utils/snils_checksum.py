"""
Утилиты для работы с СНИЛС: форматирование и проверка контрольной суммы
"""


def format_snils(d: str) -> str:
    """
    Форматирует строку из 11 цифр в формат СНИЛС: XXX-XXX-XXX XX
    
    Args:
        d: строка из 11 цифр
        
    Returns:
        Отформатированная строка в формате XXX-XXX-XXX XX
    """
    if len(d) != 11:
        return d
    return f"{d[:3]}-{d[3:6]}-{d[6:9]} {d[9:11]}"


def snils_checksum_ok(d: str) -> bool:
    """
    Проверяет контрольную сумму СНИЛС.
    
    Алгоритм:
    - Берем первые 9 цифр
    - Вычисляем сумму: s = sum(nums[i] * (9-i) for i in 0..8)
    - r = s % 101
    - Если r в (100, 101), то r = 0
    - Сравниваем r с последними 2 цифрами (формат 2 знака)
    
    Args:
        d: строка из 11 цифр
        
    Returns:
        True если контрольная сумма корректна, False иначе
    """
    if len(d) != 11 or not d.isdigit():
        return False
    
    # Первые 9 цифр
    nums = [int(d[i]) for i in range(9)]
    
    # Вычисляем сумму
    s = sum(nums[i] * (9 - i) for i in range(9))
    
    # Остаток от деления на 101
    r = s % 101
    
    # Если r в (100, 101), то r = 0
    if r in (100, 101):
        r = 0
    
    # Сравниваем с последними 2 цифрами
    last_two = int(d[9:11])
    
    return r == last_two

